/// Escribe el PNG en un archivo temporal con E/S síncrona.
///
/// `testWidgets` corre en una zona de async falso, donde un `await` de E/S real
/// nunca se completaría. Por eso los tests escriben con la variante síncrona.
File writeTinyImage() {
  final dir = Directory.systemTemp.createTempSync('catastro_test_');
  addTearDown(() {
    if (dir.existsSync()) dir.deleteSync(recursive: true);
  });
  final file = File('${dir.path}${Platform.pathSeparator}tiny.png');
  file.writeAsBytesSync(tinyPng, flush: true);
  return file;
}
